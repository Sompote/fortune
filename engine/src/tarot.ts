const REVERSE_PROB = 0.3

export function shuffle<T>(arr: T[]): T[] {
  const a = arr.slice()
  for (let i = a.length - 1; i > 0; i--) {
    const j = randomInt(0, i + 1)
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

export function drawTarot(opts: { spread?: SpreadId; question?: string; allowReversed?: boolean } = {}): TarotDraw {
  const spread = opts.spread ?? "three"
  const def = SPREADS[spread]
  if (!def) throw new Error(`unknown spread ${spread}`)
  const allowReversed = opts.allowReversed !== false
  const deck = shuffle(DECK)
  const cards: DrawnCard[] = def.positions.map((p, i) => {
    const c = deck[i]
    const reversed = allowReversed && randomInt(0, 100) < REVERSE_PROB * 100
    return { ...c, position: p.label, positionHint: p.hint, reversed, meaning: reversed ? c.rev : c.up }
  })
  const question = opts.question?.trim() || undefined
  const draw: TarotDraw = { id: `t${Date.now().toString(36)}`, date: new Date().toISOString(), spread, spreadName: def.name, question, cards, summaryThai: "" }
  draw.summaryThai = summarize(draw)
  return draw
}

export function summarize(d: TarotDraw): string {
  const lines = [`ไพ่ยิปซี ${d.spreadName}${d.question ? ` คำถาม: "${d.question}"` : ""} (เปิดเมื่อ ${d.date.slice(0, 16).replace("T", " ")} UTC)`]
  for (const c of d.cards) {
    const suit = c.suit ? ` ชุด${SUIT_THAI[c.suit].name} ธาตุ${SUIT_THAI[c.suit].element} (${SUIT_THAI[c.suit].theme})` : " ไพ่ชุดใหญ่"
    lines.push(`- ${c.position} [${c.positionHint}]: ${c.nameThai} (${c.name})${c.reversed ? " กลับหัว" : " หัวตั้ง"}${suit} → ${c.meaning}`)
  }
  const majors = d.cards.filter(c => c.arcana === "major").length
  const rev = d.cards.filter(c => c.reversed).length
  const suits = d.cards.filter(c => c.suit).map(c => SUIT_THAI[c.suit!].name)
  const dom = suits.length ? Object.entries(suits.reduce<Record<string, number>>((m, s) => ((m[s] = (m[s] ?? 0) + 1), m), {})).sort((a, b) => b[1] - a[1])[0] : null
  lines.push(`ภาพรวมสำรับ: ไพ่ชุดใหญ่ ${majors}/${d.cards.length} ใบ${majors >= Math.ceil(d.cards.length / 2) ? " (เรื่องนี้มีน้ำหนักเชิงชะตา/บทเรียนชีวิต)" : ""}, กลับหัว ${rev} ใบ${dom && dom[1] >= 2 ? `, ชุด${dom[0]}เด่น ${dom[1]} ใบ` : ""}`)
  return lines.join("\n")
}
