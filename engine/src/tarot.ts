export type Arcana = "major" | "minor"
export type Suit = "wands" | "cups" | "swords" | "pentacles"
export type SpreadId = "one" | "three" | "five"

export interface TarotCardDef {
  id: string
  name: string
  nameThai: string
  arcana: Arcana
  number: number
  suit?: Suit
  /** short upright keywords (Thai) */
  up: string
  /** short reversed keywords (Thai) */
  rev: string
  /** glyph used by the web renderer (unicode, not emoji) */
  glyph: string
}

export interface DrawnCard extends TarotCardDef {
  position: string
  positionHint: string
  reversed: boolean
  meaning: string
}

export interface TarotDraw {
  id: string
  date: string
  spread: SpreadId
  spreadName: string
  question?: string
  cards: DrawnCard[]
  summaryThai: string
}

